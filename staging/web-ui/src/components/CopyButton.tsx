import { useState, useCallback } from 'react';

interface CopyButtonProps {
  value: string;
  /** Extra classes on the button element (e.g. sizing / colour overrides) */
  className?: string;
  /** Accessible label prefix — defaults to "Copy" */
  label?: string;
}

/**
 * Inline copy-to-clipboard button.
 * Shows a clipboard icon; switches to a tick for 1.5 s after copying.
 */
export default function CopyButton({ value, className = '', label = 'Copy' }: CopyButtonProps) {
  const [copied, setCopied] = useState(false);

  const handleCopy = useCallback(async () => {
    try {
      await navigator.clipboard.writeText(value);
      setCopied(true);
      setTimeout(() => setCopied(false), 1500);
    } catch {
      // Fallback for older environments
      const el = document.createElement('textarea');
      el.value = value;
      el.style.position = 'fixed';
      el.style.opacity = '0';
      document.body.appendChild(el);
      el.select();
      document.execCommand('copy');
      document.body.removeChild(el);
      setCopied(true);
      setTimeout(() => setCopied(false), 1500);
    }
  }, [value]);

  return (
    <button
      type="button"
      onClick={handleCopy}
      title={copied ? 'Copied!' : `${label}: ${value}`}
      aria-label={copied ? 'Copied!' : `${label} to clipboard`}
      className={`inline-flex items-center justify-center w-5 h-5 rounded transition-colors flex-shrink-0
        ${copied
          ? 'text-green-500 dark:text-green-400'
          : 'text-ux-text-muted hover:text-ux-text-sub'
        } ${className}`}
    >
      {copied ? (
        /* Tick */
        <svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 20 20" fill="currentColor" className="w-3.5 h-3.5">
          <path fillRule="evenodd" d="M16.704 4.153a.75.75 0 01.143 1.052l-8 10.5a.75.75 0 01-1.127.075l-4.5-4.5a.75.75 0 011.06-1.06l3.894 3.893 7.48-9.817a.75.75 0 011.05-.143z" clipRule="evenodd" />
        </svg>
      ) : (
        /* Clipboard */
        <svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 20 20" fill="currentColor" className="w-3.5 h-3.5">
          <path fillRule="evenodd" d="M13.887 3.182c.396.037.79.08 1.183.128C16.194 3.45 17 4.414 17 5.517V16.75A2.25 2.25 0 0114.75 19h-9.5A2.25 2.25 0 013 16.75V5.517c0-1.103.806-2.068 1.93-2.207.393-.048.787-.09 1.183-.128A3.001 3.001 0 019 1h2c1.373 0 2.531.923 2.887 2.182zM7.5 4.75a.75.75 0 01.75-.75h3.5a.75.75 0 010 1.5h-3.5a.75.75 0 01-.75-.75zM10 3a1.5 1.5 0 100 3 1.5 1.5 0 000-3z" clipRule="evenodd" />
        </svg>
      )}
    </button>
  );
}
